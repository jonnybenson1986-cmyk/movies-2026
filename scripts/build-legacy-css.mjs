// Builds public/css/legacy.css: top / right / bottom / left for every `inset:` in the app's stylesheets, used only by
// engines that don't understand `inset` (Chromium before 87, which some Android TV WebViews still are). Without it the
// player, windows and other overlays lose their size on those TVs. No dependencies; run on every deploy, or by hand:
//   node scripts/build-legacy-css.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'public/css');
const SKIP = new Set(['legacy.css']);

// The CSS shorthand rule: 1 value -> all four, 2 -> vertical horizontal, 3 -> top horizontal bottom, 4 -> clockwise
export function expandInset(value) {
  const parts = [];
  let depth = 0, cur = '';
  for (const ch of value.trim()) {   // split on spaces that aren't inside calc(...) / var(...)
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (/\s/.test(ch) && depth === 0) { if (cur) parts.push(cur); cur = ''; } else cur += ch;
  }
  if (cur) parts.push(cur);
  const [t, r = t, b = t, l = r] = parts;
  return parts.length ? { top: t, right: r, bottom: b, left: l } : null;
}

// Walks a stylesheet and returns [{ at: ['@media ...'], selector, inset }] for each rule with an inset declaration
export function findInsets(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = [], stack = [];
  let i = 0, start = 0;
  while (i < css.length) {
    const ch = css[i];
    if (ch === '{') {
      stack.push({ prelude: css.slice(start, i).trim(), bodyStart: i + 1, hasChild: false });
      if (stack.length > 1) stack[stack.length - 2].hasChild = true;
      start = i + 1;
    } else if (ch === '}') {
      const block = stack.pop();
      if (block && !block.hasChild && !block.prelude.startsWith('@')) {
        const body = css.slice(block.bodyStart, i);
        const m = /(?:^|;)\s*inset\s*:\s*([^;!]+)(!important)?/.exec(body);
        if (m) out.push({ at: stack.map(s => s.prelude).filter(p => p.startsWith('@')), selector: block.prelude, inset: m[1].trim(), important: !!m[2] });
      }
      start = i + 1;
    } else if (ch === ';' && stack.length === 0) start = i + 1;
    i++;
  }
  return out;
}

export function buildLegacyCss(files) {
  const rules = [];
  for (const [name, css] of files) {
    for (const r of findInsets(css)) {
      const v = expandInset(r.inset);
      if (!v || /keyframes/i.test(r.at.join(' '))) continue;
      const imp = r.important ? ' !important' : '';
      const decl = `top: ${v.top}${imp}; right: ${v.right}${imp}; bottom: ${v.bottom}${imp}; left: ${v.left}${imp};`;
      let rule = `${r.selector} { ${decl} }`;
      for (const at of [...r.at].reverse()) rule = `${at} { ${rule} }`;
      rules.push(`/* ${name} */ ${rule}`);
    }
  }
  return `/* Generated by scripts/build-legacy-css.mjs. Do not edit: run the script after changing a stylesheet.
   The long-hand version of every \`inset\` in the app, for engines that don't support \`inset\` (Chromium < 87). */
@supports not (inset: 0) {
${rules.map(r => '  ' + r).join('\n')}
}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = readdirSync(dir).filter(f => f.endsWith('.css') && !SKIP.has(f)).sort().map(f => [f, readFileSync(join(dir, f), 'utf8')]);
  const css = buildLegacyCss(files);
  writeFileSync(join(dir, 'legacy.css'), css);
  console.log(`public/css/legacy.css: ${css.split('\n').length - 4} rules`);
}
